/** Regenerate src/lib/kpi/demo-catalog-samples.ts from the demo database.
 * Runs every canned KPI's metric SQL in a read-only transaction and stores the rows as the
 * instant-preview sample. Run after re-seeding demo/seed.sql.
 * Usage: DEMO_DATABASE_URL=postgresql://… node scripts/refresh-demo-catalog-samples.mjs
 */
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import jiti from 'jiti';
import pg from 'pg';

const url = process.env.DEMO_DATABASE_URL;
if (!url) throw new Error('Set DEMO_DATABASE_URL (the read-only demo role is enough).');

const load = jiti(import.meta.url, { alias: { '@': resolve('src') }, interopDefault: true });
const { DEMO_KPI_PROPOSALS } = load('../src/lib/kpi/demo-catalog.ts');
const { normalizeDemoRow, wholeDayRows } = load('../src/lib/demo/board-rows.ts');

// Keep DATE columns as 'YYYY-MM-DD' text; the default parser shifts them through local time.
pg.types.setTypeParser(1082, (value) => value);
const client = new pg.Client({ connectionString: url });
await client.connect();
const today = (await client.query("select current_date::text as d")).rows[0].d;

const samples = {};
try {
  for (const proposal of DEMO_KPI_PROPOSALS) {
    await client.query('begin read only');
    const result = await client.query(proposal.metricSql);
    await client.query('rollback');
    const columns = result.fields.map((field) => field.name);
    const rows = wholeDayRows(result.rows.map((row) => normalizeDemoRow(row, columns)), proposal.metricSql, today);
    samples[proposal.key] = { columns, rows };
  }
} finally {
  await client.end();
}

const file = resolve('src/lib/kpi/demo-catalog-samples.ts');
await writeFile(file, `// Generated by scripts/refresh-demo-catalog-samples.mjs from the demo database (${today}).
// Instant-preview rows for DEMO_KPI_PROPOSALS; live widgets re-run the SQL. Do not edit by hand.
import type { VisualizationSpec } from '@/lib/viz/spec'

type Sample = NonNullable<VisualizationSpec['sample']>

export const DEMO_KPI_SAMPLES: Record<string, Sample> = {
${Object.entries(samples).map(([key, sample]) => `  ${key}: {
    columns: ${JSON.stringify(sample.columns)},
    rows: [
${sample.rows.map((row) => `      ${JSON.stringify(row)},`).join('\n')}
    ],
  },`).join('\n')}
}
`);
console.log(`Wrote ${Object.keys(samples).length} samples to ${file}`);
