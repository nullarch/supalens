#!/usr/bin/env node
// Writes .env for the bundled self-hosted stack (docker-compose.yml): the address, the Anthropic
// key, and every secret the stack needs, generated here. Run through ./selfhost.sh, or directly:
//
//   APP_URL=https://bi.example.com ANTHROPIC_API_KEY=sk-ant-… node scripts/selfhost-init.mjs
//
// It never overwrites an existing .env: the generated keys encrypt stored credentials and sign
// sessions, so regenerating them would lock an existing install out of its own data.
import { createHmac, randomBytes } from 'node:crypto'
import { existsSync, writeFileSync } from 'node:fs'

const ENV_PATH = process.env.SUPALENS_ENV_FILE || '.env'

if (existsSync(ENV_PATH)) {
  console.log(`${ENV_PATH} already exists — leaving it untouched.`)
  process.exit(0)
}

const appUrl = (process.env.APP_URL || 'http://localhost:8080').trim().replace(/\/+$/, '')
let parsed
try {
  parsed = new URL(appUrl)
} catch {
  console.error(`APP_URL is not a valid URL: ${appUrl}`)
  process.exit(1)
}
if (!['http:', 'https:'].includes(parsed.protocol) || parsed.pathname !== '/') {
  console.error('APP_URL must be an http(s) origin without a path, e.g. https://bi.example.com')
  process.exit(1)
}

const anthropicKey = (process.env.ANTHROPIC_API_KEY || '').trim()
if (!anthropicKey) console.warn('No Anthropic key given — set ANTHROPIC_API_KEY or the LLM_* variables in .env before asking questions.')

const b64url = (input) => Buffer.from(input).toString('base64url')

/** A Supabase API key is a JWT signed with the project's JWT secret, carrying only a role. */
function apiKey(role, secret) {
  const now = Math.floor(Date.now() / 1000)
  const header = b64url(JSON.stringify({ alg: 'HS256', typ: 'JWT' }))
  const payload = b64url(JSON.stringify({ role, iss: 'supabase', iat: now, exp: now + 10 * 365 * 24 * 60 * 60 }))
  const signature = createHmac('sha256', secret).update(`${header}.${payload}`).digest('base64url')
  return `${header}.${payload}.${signature}`
}

const jwtSecret = randomBytes(48).toString('base64url')
const port = process.env.PORT || (parsed.hostname === 'localhost' || parsed.hostname === '127.0.0.1' ? parsed.port || '8080' : '8080')

const lines = [
  '# Supalens self-hosted — generated by scripts/selfhost-init.mjs.',
  '# Keep this file private and BACK IT UP: KEK_LOCAL_MASTER_KEY encrypts every stored database',
  '# credential and cannot be recovered if lost.',
  '',
  '# The address people open. Changing it means rebuilding: docker compose up --build -d',
  `NEXT_PUBLIC_APP_URL=${appUrl}`,
  '# Host port the stack listens on.',
  `PORT=${port}`,
  '',
  '# The model behind the agents. Either an Anthropic key …',
  `ANTHROPIC_API_KEY=${anthropicKey}`,
  '# … or any OpenAI-compatible endpoint (OpenAI, Gemini, OpenRouter, Ollama, vLLM, …):',
  '# LLM_PROVIDER=openai',
  '# LLM_BASE_URL=https://api.openai.com/v1',
  '# LLM_API_KEY=',
  '# LLM_MODEL=',
  '',
  '# ── Generated secrets — do not change after the first start ──',
  `POSTGRES_PASSWORD=${randomBytes(24).toString('hex')}`,
  `JWT_SECRET=${jwtSecret}`,
  `NEXT_PUBLIC_SUPABASE_ANON_KEY=${apiKey('anon', jwtSecret)}`,
  `SUPABASE_SERVICE_ROLE_KEY=${apiKey('service_role', jwtSecret)}`,
  'KEK_PROVIDER=local',
  `KEK_LOCAL_MASTER_KEY=${randomBytes(32).toString('base64')}`,
  '',
  '# ── Optional ──',
  '# Mail (alerts, digests) through your own mail server:',
  '# SMTP_URL=smtp://user:password@mail.example.com:587',
  '# EMAIL_FROM="Supalens <bi@example.com>"',
  '# Block databases on private/loopback addresses (allowed by default on a self-hosted install):',
  '# ALLOW_PRIVATE_DB_HOSTS=false',
  '',
]

writeFileSync(ENV_PATH, lines.join('\n'), { mode: 0o600 })
console.log(`Wrote ${ENV_PATH} for ${appUrl}`)
